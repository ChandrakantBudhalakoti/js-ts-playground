// Prepares static assets served from our own origin (no CDN), at versioned,
// immutable paths under public/vendor/:
//
// 1. monaco-editor's prebuilt AMD bundle  -> public/vendor/monaco/<version>/vs
// 2. the TypeScript lib .d.ts files the compiler worker needs (the roots in
//    src/lib/compiler/lib-roots.json plus everything they reference)
//                                         -> public/vendor/typescript/<version>/lib.json
// 3. the WebAssembly language runtimes and Clang listed in
//    src/lib/runtime/runtime-assets.json, gzipped (the app decompresses them,
//    so transfers stay small whatever the host does), with an index.json of
//    file sizes                           -> public/vendor/runtimes/<id>/<version>/
//
// Runs on predev and prebuild (strict), and on postinstall with --optional:
// a production-only install (`npm ci --omit=dev`) has no `typescript`, and
// must not fail because of it; the assets were generated by the build.
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const vendor = join(root, "public", "vendor");

// Some packages' "exports" maps hide package.json, so walk up from the entry
// point; others have no entry point at all, but expose package.json.
function findPackageRoot(name) {
  let entry;
  try {
    entry = require.resolve(name);
  } catch {
    return dirname(require.resolve(`${name}/package.json`));
  }
  for (let dir = dirname(entry); dir !== dirname(dir); dir = dirname(dir)) {
    const candidate = join(dir, "package.json");
    if (
      existsSync(candidate) &&
      JSON.parse(readFileSync(candidate, "utf8")).name === name
    )
      return dir;
  }
  throw new Error(`Could not find the ${name} package`);
}

function versionOf(packageRoot) {
  return JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"))
    .version;
}

/** Remove every version directory except the current one. */
function prune(dir, keep) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir)) {
    if (entry !== keep)
      rmSync(join(dir, entry), { recursive: true, force: true });
  }
}

function copyMonaco() {
  const packageRoot = findPackageRoot("monaco-editor");
  const version = versionOf(packageRoot);
  const target = join(vendor, "monaco", version, "vs");
  prune(join(vendor, "monaco"), version);
  if (existsSync(join(target, "loader.js"))) {
    console.log(`monaco-editor ${version}: up to date`);
    return;
  }
  cpSync(join(packageRoot, "min", "vs"), target, { recursive: true });
  console.log(
    `monaco-editor ${version}: copied to public/vendor/monaco/${version}/vs`,
  );
}

function bundleTypeScriptLibs() {
  const packageRoot = findPackageRoot("typescript");
  const version = versionOf(packageRoot);
  const libDir = join(packageRoot, "lib");
  const roots = JSON.parse(
    readFileSync(
      join(root, "src", "lib", "compiler", "lib-roots.json"),
      "utf8",
    ),
  );
  const reference = /^\/\/\/\s*<reference\s+lib=["']([^"']+)["']\s*\/>/gm;

  const files = {};
  const queue = [...roots];
  while (queue.length > 0) {
    const name = queue.shift();
    if (name in files) continue;
    const content = readFileSync(join(libDir, name), "utf8");
    files[name] = content;
    for (const match of content.matchAll(reference))
      queue.push(`lib.${match[1].toLowerCase()}.d.ts`);
  }

  const outDir = join(vendor, "typescript", version);
  prune(join(vendor, "typescript"), version);
  mkdirSync(outDir, { recursive: true });
  const json = JSON.stringify(files);
  writeFileSync(join(outDir, "lib.json"), json);
  console.log(
    `typescript ${version}: bundled ${Object.keys(files).length} lib files (${Math.round(json.length / 1024)} KB)`,
  );
}

/**
 * Version of the published layout. Raise it when the way files are written
 * changes, so existing copies are regenerated rather than kept as up to date.
 */
const INDEX_FORMAT = 2;

/** `{ [published name]: path in the package }` for a spec's files and directories. */
function runtimeFiles(packageRoot, spec) {
  const files = { ...spec.files };
  for (const [prefix, { from, exclude }] of Object.entries(
    spec.directories ?? {},
  )) {
    const skip = exclude ? new RegExp(exclude) : null;
    const walk = (dir) => {
      for (const entry of readdirSync(join(packageRoot, from, dir), {
        withFileTypes: true,
      })) {
        const relative = dir ? `${dir}/${entry.name}` : entry.name;
        if (entry.isDirectory()) walk(relative);
        else if (!skip?.test(relative))
          files[`${prefix}/${relative}`] = `${from}/${relative}`;
      }
    };
    walk("");
  }
  return files;
}

function copyRuntime(id, spec) {
  // A runtime published as an npm package, or kept in this repository
  // (`path`, e.g. runtimes/java: TeaVM publishes no package).
  const packageRoot = spec.path
    ? join(root, spec.path)
    : findPackageRoot(spec.package);
  const version = spec.path ? spec.version : versionOf(packageRoot);
  if (version !== spec.version) {
    throw new Error(
      `${spec.package} ${version} is installed, but src/lib/runtime/runtime-assets.json expects ${spec.version}. ` +
        "Update the version there (the runtime drivers are tested against it).",
    );
  }
  const outDir = join(vendor, "runtimes", id, version);
  prune(join(vendor, "runtimes", id), version);
  const indexPath = join(outDir, "index.json");
  const sources = runtimeFiles(packageRoot, spec);
  const names = Object.keys(sources);
  if (existsSync(indexPath)) {
    const index = JSON.parse(readFileSync(indexPath, "utf8"));
    const published = Object.keys(index.files);
    if (
      index.format === INDEX_FORMAT &&
      published.length === names.length &&
      names.every((name) => name in index.files)
    ) {
      console.log(`${spec.package} ${version}: up to date`);
      return;
    }
    // The file list changed: start this version over.
    rmSync(outDir, { recursive: true, force: true });
  }
  mkdirSync(outDir, { recursive: true });
  const plain = new Set(spec.uncompressed ?? []);
  const files = {};
  for (const [name, source] of Object.entries(sources)) {
    const bytes = readFileSync(join(packageRoot, source));
    mkdirSync(dirname(join(outDir, name)), { recursive: true });
    const gzipped = plain.has(name) ? null : gzipSync(bytes, { level: 9 });
    // Data that is already compressed (webR's .gz files) barely shrinks:
    // publish it as is, so browsers do not decompress it a second time.
    if (!gzipped || gzipped.length > bytes.length * 0.95) {
      writeFileSync(join(outDir, name), bytes);
      files[name] = { size: bytes.length };
    } else {
      writeFileSync(join(outDir, `${name}.gz`), gzipped);
      files[name] = { size: bytes.length, gzip: gzipped.length };
    }
  }
  // Written last: its presence marks a complete copy.
  writeFileSync(
    indexPath,
    JSON.stringify({ format: INDEX_FORMAT, version, files }),
  );
  const total = Object.values(files).reduce(
    (sum, file) => sum + (file.gzip ?? file.size),
    0,
  );
  console.log(
    `${spec.package} ${version}: copied ${names.length} files to public/vendor/runtimes/${id}/${version} (${(total / 1e6).toFixed(1)} MB)`,
  );
}

const optional = process.argv.includes("--optional");

const runtimeSpecs = JSON.parse(
  readFileSync(
    join(root, "src", "lib", "runtime", "runtime-assets.json"),
    "utf8",
  ),
);

for (const [name, step] of [
  ["monaco-editor", copyMonaco],
  ["typescript", bundleTypeScriptLibs],
  ...Object.entries(runtimeSpecs).map(([id, spec]) => [
    spec.package,
    () => copyRuntime(id, spec),
  ]),
]) {
  try {
    step();
  } catch (error) {
    const missing =
      error?.code === "MODULE_NOT_FOUND" ||
      /Could not find the .* package/.test(String(error?.message));
    if (optional && missing) {
      console.warn(
        `prepare-assets: skipped ${name} assets (package not installed). ` +
          "Run `npm run build` with dev dependencies to generate them.",
      );
      continue;
    }
    throw error;
  }
}
